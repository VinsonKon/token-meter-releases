"""Compile measured video motion into a tiny periodic corner/edge/center LUT."""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "firmware/assets/approval-motion.json")
    parser.add_argument("--output", type=Path, default=ROOT / "firmware/include/approval_reference.h")
    args = parser.parse_args()
    measured = json.loads(args.input.read_text(encoding="utf-8"))
    samples = measured["samples"]
    period, step = measured["period_ms"], measured["step_ms"]
    if (period <= 0 or step <= 0 or len(samples) < 2 or
            len(samples) * step != period or
            measured["columns"] != ["corners", "edges", "center"]):
        raise ValueError("Invalid periodic corner/edge/center sample layout")
    if any(len(row) != 3 or any(not math.isfinite(v) or not 0 <= v <= 1 for v in row) for row in samples):
        raise ValueError("Motion amplitudes must be finite and in [0,1]")
    quantized = [[int(v * 255 + 0.5) for v in row] for row in samples]
    digest = hashlib.sha256(args.input.read_bytes()).hexdigest()
    header = (
        "#pragma once\n\n#include <stdint.h>\n\n"
        "// Generated by tools/build-approval-motion.py; do not edit by hand.\n"
        f"// Measurement SHA-256: {digest}\n"
        f"// Source video SHA-256: {measured['source_sha256']}\n"
        "// User clip 14.9-18.3s: stable ring/corners/center/cross motion only.\n"
        "// Average of three source cycles at 15.19s + n*0.7s; one sample/20ms.\n"
        "// Columns: corners, edge middles, center. Warm-red tint remains runtime-owned.\n"
        "namespace approval_reference {\n\n"
        f"constexpr uint32_t kCycleMs = {period};\n"
        f"constexpr uint32_t kStepMs = {step};\n"
        f"constexpr uint16_t kSampleCount = {len(samples)};\n"
        "static const uint8_t kSamples[][3] = {\n"
        + "\n".join("    {" + ", ".join(map(str, row)) + "}," for row in quantized)
        + "\n};\n\n"
        "static_assert(kSampleCount * kStepMs == kCycleMs, \"approval motion timing mismatch\");\n"
        "}  // namespace approval_reference\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header, encoding="utf-8", newline="\n")
    print(f"Compiled {len(samples)} x 3 amplitudes / {period}ms -> {args.output}")


if __name__ == "__main__":
    main()
