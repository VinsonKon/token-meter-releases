"""Compile the measured Reading file square-breath curve for the stale glyph."""

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "firmware/assets/reading-motion.json")
    parser.add_argument("--output", type=Path, default=ROOT / "firmware/include/reading_reference.h")
    args = parser.parse_args()
    measured = json.loads(args.input.read_text(encoding="utf-8"))
    samples = measured["samples"]
    period, step = measured["period_ms"], measured["step_ms"]
    if (not isinstance(period, int) or not isinstance(step, int) or
            period <= 0 or step <= 0 or len(samples) < 2 or
            len(samples) * step != period):
        raise ValueError("Invalid periodic light sample timing")
    if (measured.get("sample_encoding") != "uint8" or
            any(type(value) is not int or not 0 <= value <= 255 for value in samples)):
        raise ValueError("Light amplitudes must be uint8 integers in [0,255]")
    quantized = samples
    rows = ["    " + ", ".join(map(str, quantized[start:start + 15])) + ","
            for start in range(0, len(quantized), 15)]
    digest = hashlib.sha256(args.input.read_bytes()).hexdigest()
    header = (
        "#pragma once\n\n#include <stdint.h>\n\n"
        "// Generated by tools/build-reading-motion.py; do not edit by hand.\n"
        f"// Measurement SHA-256: {digest}\n"
        f"// Source video SHA-256: {measured['source_sha256']}\n"
        "// User clip 11.7-14.9s: fixed solid square and co-phased soft halo.\n"
        "// Source light samples exclude text/color transitions; gold tint is runtime-owned.\n"
        "namespace reading_reference {\n\n"
        f"constexpr uint32_t kCycleMs = {period};\n"
        f"constexpr uint32_t kStepMs = {step};\n"
        f"constexpr uint16_t kSampleCount = {len(quantized)};\n"
        "static const uint8_t kLightSamples[] = {\n"
        + "\n".join(rows) + "\n};\n\n"
        "static_assert(kSampleCount * kStepMs == kCycleMs, \"reading motion timing mismatch\");\n"
        "static_assert(sizeof(kLightSamples) == kSampleCount, \"reading motion sample count mismatch\");\n"
        "}  // namespace reading_reference\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header, encoding="utf-8", newline="\n")
    print(f"Compiled {len(samples)} light samples / {period}ms -> {args.output}")


if __name__ == "__main__":
    main()
