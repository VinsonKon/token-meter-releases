"""Generate the AA4 Sofia Pro Bold 28 subset from a locally supplied font."""
from pathlib import Path
import hashlib
import argparse

from PIL import Image, ImageDraw, ImageFont


parser = argparse.ArgumentParser()
parser.add_argument("font", type=Path, help="User-supplied SofiaPro-Bold.ttf")
parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "firmware/include/sofia_bold28.h")
args = parser.parse_args()
SOURCE = args.font
OUTPUT = args.output
font = ImageFont.truetype(str(SOURCE), 28)
bitmap = []
glyphs = []
for code in range(32, 127):
    char = chr(code)
    left, top, right, bottom = font.getbbox(char, anchor="ls")
    width, height = right - left, bottom - top
    advance = round(font.getlength(char))
    glyphs.append((len(bitmap), width, height, advance, left, top))
    if not width or not height:
        continue
    mask = Image.new("L", (width, height), 0)
    ImageDraw.Draw(mask).text((-left, -top), char, font=font, fill=255, anchor="ls")
    alpha = [(value * 15 + 127) // 255 for value in mask.tobytes()]
    if len(alpha) % 2:
        alpha.append(0)
    bitmap.extend((alpha[i] << 4) | alpha[i + 1] for i in range(0, len(alpha), 2))

lines = [
    "#pragma once",
    "// Genuine Sofia Pro Bold at 28px, ASCII 32..126.",
    "// Generated by tools/build-sofia-bold28.py using Pillow FreeType.",
    "// Alpha is quantized to 4 bits, high nibble first; each glyph is byte aligned.",
    "// Source SHA256: " + hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
    '#include "sofia_aa_fonts.h"',
    "",
    "const uint8_t SofiaBold28Bitmaps[] PROGMEM = {",
]
for start in range(0, len(bitmap), 16):
    lines.append("  " + ", ".join(f"0x{value:02X}" for value in bitmap[start:start + 16]) + ",")
lines.extend(["};", "", "const AA4Glyph SofiaBold28Glyphs[] PROGMEM = {"])
for code, glyph in zip(range(32, 127), glyphs):
    lines.append("  {" + ", ".join(map(str, glyph)) + "}, // U+" + f"{code:04X}")
ascent, descent = font.getmetrics()
lines.extend([
    "};", "",
    "const AA4Font SofiaBold28 PROGMEM = {",
    f"  SofiaBold28Bitmaps, SofiaBold28Glyphs, 32, 126, {ascent + descent}",
    "};", "",
])
OUTPUT.write_text("\n".join(lines), encoding="utf-8")

assert len(glyphs) == 95
for index, (offset, width, height, *_rest) in enumerate(glyphs):
    expected_next = offset + (width * height + 1) // 2
    actual_next = glyphs[index + 1][0] if index + 1 < len(glyphs) else len(bitmap)
    assert expected_next == actual_next
text = "WAITING FOR SYNC"
text_width = sum(glyphs[ord(char) - 32][3] for char in text)
assert text_width == 254
print(f"Generated: {OUTPUT}")
print(f"Glyphs={len(glyphs)}, bitmap bytes={len(bitmap)}, yAdvance={ascent + descent}")
print(f"WAITING FOR SYNC advance={text_width}px, baseline bbox={font.getbbox(text, anchor='ls')}")


