"""Compile the supplied GIF's icon into directly sampled 8-bit light frames.

Only the 100x100 icon area is retained; the reference's Thinking text is not
baked into the device. The output is a generated firmware asset, not a video
decoder. Requires the existing desktop build environment's Pillow dependency.
"""

import argparse
import hashlib
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SIZE = 64
CROP = (110, 2, 210, 102)
# The GIF begins with a solid-square entrance, not a cyclic shape. Frames
# 45 and 86 are the same phase of its later forward-moving glyph cycle;
# retaining [45, 86) closes that natural cycle without reversing or holding
# duplicate endpoints. Playback is 323/150 of the original 3230ms cadence,
# giving exactly 1500ms per loop without changing the independent tint.
SOURCE_FIRST_FRAME = 45
SOURCE_CYCLE_END_FRAME = 86  # Exclusive; this next source frame matches phase 45.
PLAYBACK_SPEED_NUMERATOR = 323
PLAYBACK_SPEED_DENOMINATOR = 150


def array(name, ctype, values, columns=16, hexadecimal=False):
    rows = []
    for offset in range(0, len(values), columns):
        items = values[offset:offset + columns]
        rows.append("    " + ", ".join(
            f"0x{value:04x}" if hexadecimal else str(value) for value in items
        ) + ",")
    return f"static const {ctype} {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gif", type=Path, default=ROOT / "firmware/assets/thinking-reference.gif")
    parser.add_argument("--output", type=Path, default=ROOT / "firmware/include/thinking_reference.h")
    args = parser.parse_args()
    source = Image.open(args.gif)
    if source.size != (592, 112):
        raise ValueError("The verified crop requires the supplied 592x112 GIF")
    if source.n_frames <= SOURCE_CYCLE_END_FRAME:
        raise ValueError("The verified natural loop requires source frames 45 through 86")
    frames, ends = [], []
    elapsed = 0
    for index in range(source.n_frames):
        source.seek(index)
        # Match ordinary GIF playback: invalid/very short delays use 100 ms.
        # This is also FFmpeg GIF's min_delay=2/default_delay=10 policy.
        duration = source.info.get("duration", 0)
        elapsed += duration if duration >= 20 else 100
        ends.append(elapsed)
        frame = source.convert("RGB").crop(CROP).resize((SIZE, SIZE), Image.Resampling.LANCZOS)
        frames.append(frame)

    atlas = Image.new("RGB", (SIZE, SIZE * len(frames)))
    for index, frame in enumerate(frames):
        atlas.paste(frame, (0, index * SIZE))
    palette = atlas.quantize(colors=255, method=Image.Quantize.MEDIANCUT).getpalette()[:255 * 3]
    palette_image = Image.new("P", (1, 1))
    palette_image.putpalette([0, 0, 0] + palette)
    rgb565 = [
        ((r & 248) << 8) | ((g & 252) << 3) | (b >> 3)
        for r, g, b in zip(*[iter([0, 0, 0] + palette)] * 3)
    ]
    # Match the previous RGB565 palette's normalized peak intensity before
    # storing one byte per pixel. This retains the original soft glow while
    # allowing adjacent frames to be interpolated without RLE decoding.
    palette_light = [
        int(max(((color >> 11) & 31) / 31,
                ((color >> 5) & 63) / 63,
                (color & 31) / 31) * 255 + 0.5)
        for color in rgb565
    ]
    # Keep the full-source palette above, so cropping does not re-quantize the
    # selected shapes. Scale cumulative endpoints rather than each duration
    # separately, avoiding accumulated millisecond rounding errors.
    cycle_frames = frames[SOURCE_FIRST_FRAME:SOURCE_CYCLE_END_FRAME]
    source_start_ms = ends[SOURCE_FIRST_FRAME - 1]
    source_cycle_ms = ends[SOURCE_CYCLE_END_FRAME - 1] - source_start_ms
    cycle_ends = [
        ((end - source_start_ms) * PLAYBACK_SPEED_DENOMINATOR
         + PLAYBACK_SPEED_NUMERATOR // 2) // PLAYBACK_SPEED_NUMERATOR
        for end in ends[SOURCE_FIRST_FRAME:SOURCE_CYCLE_END_FRAME]
    ]
    data = []
    for frame in cycle_frames:
        pixels = frame.quantize(palette=palette_image, dither=Image.Dither.NONE).tobytes()
        data.extend(palette_light[index] for index in pixels)

    digest = hashlib.sha256(args.gif.read_bytes()).hexdigest()
    header = (
        "#pragma once\n\n#include <stdint.h>\n\n"
        "// Generated by tools/build-thinking-reference.py; do not edit by hand.\n"
        f"// Source SHA-256: {digest}\n"
        "// Crop (110,2)-(210,102), 64x64, direct frame-major 8-bit light.\n"
        "// Light is the previous RGB565 palette's normalized peak; zero is transparent.\n"
        "// Natural forward cycle: GIF [45,86), without its non-looping square entrance.\n"
        f"// Original cycle {source_cycle_ms} ms at {PLAYBACK_SPEED_NUMERATOR}/"
        f"{PLAYBACK_SPEED_DENOMINATOR}x = {cycle_ends[-1]} ms; independent tint is unchanged.\n"
        "namespace thinking_reference {\n\n"
        f"constexpr uint16_t kSize = {SIZE};\n"
        f"constexpr uint32_t kFramePixels = {SIZE * SIZE};\n"
        f"constexpr uint16_t kFrameCount = {len(cycle_frames)};\n"
        f"constexpr uint32_t kDurationMs = {cycle_ends[-1]};\n"
        f"constexpr uint16_t kSourceFirstFrame = {SOURCE_FIRST_FRAME};\n"
        f"constexpr uint16_t kSourceCycleEndFrame = {SOURCE_CYCLE_END_FRAME}; // Exclusive\n"
        f"constexpr uint32_t kSourceCycleDurationMs = {source_cycle_ms};\n"
        f"constexpr uint16_t kPlaybackSpeedNumerator = {PLAYBACK_SPEED_NUMERATOR};\n"
        f"constexpr uint16_t kPlaybackSpeedDenominator = {PLAYBACK_SPEED_DENOMINATOR};\n\n"
        + array("kFrameEnds", "uint32_t", cycle_ends)
        + array("kLightFrames", "uint8_t", data, columns=24)
        + "\n}  // namespace thinking_reference\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header, encoding="utf-8", newline="\n")
    print(f"Compiled source [{SOURCE_FIRST_FRAME},{SOURCE_CYCLE_END_FRAME}): "
          f"{len(cycle_frames)} frames / {source_cycle_ms} ms at "
          f"{PLAYBACK_SPEED_NUMERATOR}/{PLAYBACK_SPEED_DENOMINATOR}x = "
          f"{cycle_ends[-1]} ms / {len(data)} direct light bytes -> {args.output}")


if __name__ == "__main__":
    main()
